// Пакет geo — представление L2J-геодаты (файлы «NN_NN.l2j» формата Mobius
// Interlude): декодер над байтами региона, хранение вне Go-кучи и O(1)-лукапы
// ячеек без аллокаций.
//
// Формат и семантика чтения — порт GeoEngine канона Mobius (GPL,
// org.l2jmobius.gameserver.geoengine): константы, раскладка блоков, алгоритмы
// ближайшего слоя; источники — в doc-комментариях определений.
//
// Контракты владения:
//
//   - DecodeRegion не копирует байты: Region ссылается на переданный слайс,
//     время жизни слайса обязано покрывать время жизни Region.
//   - LoadDir отображает файлы через mapFile и владеет отображениями
//     установленных регионов до конца жизни процесса: unmap не вызывается.
//     Отображение несостоявшегося региона освобождается.
//   - Предусловие оператора: каталог геодаты не модифицируется и не усекается
//     при живых отображениях (нарушение — SIGBUS/ACCESS_VIOLATION вне
//     контроля Go).
//
// Правило канона getNearestZ: «ближайший слой, но при превышении +1000 — слой
// ниже» применяется ТОЛЬКО к multilayer-блокам (порт
// MultilayerBlock.getNearestZ; flat/complex возвращают высоту безусловно).
// Композиция правила — задача потребителя движения; здесь оно зафиксировано,
// чтобы не потерялось между задачами.
