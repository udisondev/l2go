// Package encode — стейтлес-стадия энкода исходящего (ADR-0004): сборка
// per-client FIFO кадров в слэбы вызывающего; пакеты-писатели protocol пишут
// прямо в слэб (модель владения буфером interlude — r4: малые пакеты — стек,
// крупные — pkg/bufpool). Работает вне тика; криптоблок — батч кадра.
// Реализация — фазы 3–4.
package encode

// Frame — исходящий кадр клиента в пер-клиентском FIFO (payload уже собран
// пакетом-писателем; encode-once для побайтово одинаковых кадров — эволюция
// фазы 6 из ADR-0004).
type Frame struct {
	ClientID uint32
	Payload  []byte
}
