// Package protocol — бинарный слой протокола Interlude 746: каталог опкодов
// (494 записи по шести группам направлений), примитивы кодека и типизированные
// пакеты логин-флоу, хендшейка и боя. Форма каждого пакета определяется ролью
// потребителя, а не направлением пакета: кодирование исходящего — функция-писатель
// func(dst []byte, args ...) int, пишущая с опкодом в буфер вызывающего и
// возвращающая число записанных байт (малые пакеты — стек вызывающего,
// крупные — пул буферов; размер строковых полей считает LenS, вариабельных
// пакетов — их Size-функции); разбор входящего — представление type Name []byte
// с конструктором, проверяющим минимальную длину один раз, и геттерами по
// офсетам без копий. Нулевое значение представления недействительно: доступ к
// полям — только после успешного конструктора. Читатели примитивов возвращают
// (значение, ok) и не паникуют на недоверенных буферах; писатели паникуют с
// диагностикой только при нарушении программного контракта (короткий dst);
// данные пользователя (длины строк учётных данных) — ошибкой, не паникой.
// Переменно-структурные представления (списки записей, строки перед хвостом)
// проверяют в конструкторе только заголовок: навигационные геттеры и геттеры
// после строк возвращают (значение, ok), частичный разбор лучше отказа —
// диспетчер показывает остаток hex-дампом.
