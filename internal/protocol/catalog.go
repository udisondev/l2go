// udisondev/interlude@34fe4c8657d8b6bf338a5d2e788e194489a44f8f docs/opcodes.md;
// значения сверены с L2J Mobius master CT_0_Interlude (зеркало
// gitlab.com/expcero/L2J_Mobius, 43ac8878f582ea792874eb74df16e2b0b64990e6):
// расхождений значений нет; имена расходятся в 8 косметических нормализациях
// C→GameServer (например REQUEST_BBS_WRITE против REQUEST_B_B_SWRITE при
// одинаковом значении) — приняты имена интерлюда. Перенесены имя и значение;
// колонки категория/описание/статус исходника — нет.
//
// У основных групп Value — опкод (один байт), у Ex-групп Value — sub при
// опкоде семейства (0xD0 C→GameServer, 0xFE GameServer→C; запись 0xD0 в
// основной C→GameServer-таблице — легитимный EX_PACKET-признак семейства).
// sub=0 означает «нет sub» — в обеих Ex-группах значения начинаются с 0x01.

// opcodeDef — запись каталога: имя пакета как в источнике и его значение
// (опкод или sub Ex-семейства).
type opcodeDef struct {
	Name  string
	Value uint16
}

